import { Resend } from "resend";
import { env } from "~/env";
import type { Triage } from "~/lib/triage-parse";

const resend = new Resend(env.RESEND_API_KEY);

export type ContactSubmissionData = {
  id: string;
  name: string;
  organisation?: string | null;
  email: string;
  phone?: string | null;
  service?: string | null;
  message: string;
};

// Everything a visitor typed is escaped before it goes into the email.
export const esc = (s: string) =>
  s
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");

const oneLine = (s: string) =>
  s
    .replace(/[\r\n\u2028\u2029]+/g, " ")
    .replace(/\s+/g, " ")
    .trim();

const multiline = (s: string) => esc(s).replace(/\r?\n/g, "<br>");

// Blank or missing values show as a dash in the email.
function orDash(value?: string | null): string {
  const trimmed = value?.trim();
  if (!trimmed) return "—";
  return trimmed;
}

const BADGE = {
  high: { label: "HIGH PRIORITY", bg: "#FEE4E2", fg: "#B42318" },
  medium: { label: "MEDIUM", bg: "#FEF0C7", fg: "#93370D" },
  low: { label: "LOW", bg: "#E8EDEA", fg: "#0D4A3A" },
  spam: { label: "POSSIBLE SPAM", bg: "#EAECF0", fg: "#475467" },
  none: { label: "NOT TRIAGED", bg: "#EAECF0", fg: "#475467" },
} as const;

export function buildContactEmail(
  s: ContactSubmissionData,
  triage: Triage | null,
  adminUrl: string,
) {
  const badge = BADGE[triage?.priority ?? "none"];
  const tag = triage ? `[${triage.priority.toUpperCase()}]` : "[NEW]";
  const subject = oneLine(
    `${tag} New enquiry from ${s.name}${s.service ? ` — ${s.service}` : ""}`,
  ).slice(0, 150);

  const rows: [string, string][] = [
    ["Name", s.name],
    ["Organisation", orDash(s.organisation)],
    ["Email", s.email],
    ["Phone", orDash(s.phone)],
    ["Service", orDash(s.service)],
  ];

  const facts = triage?.keyFacts ?? [];

  const summaryBlock = triage
    ? `<div style="margin:0 0 20px;padding:16px 20px;background:#F2F5F3;border:1px solid #C8D0CC;border-radius:12px;">
        <p style="margin:0 0 8px;font-size:12px;font-weight:600;color:#2A8C6E;letter-spacing:2px;text-transform:uppercase;">AI summary${triage.category ? ` · ${esc(triage.category)}` : ""}</p>
        <p style="margin:0;font-size:15px;line-height:1.6;color:#2E2E2E;">${esc(triage.summary)}</p>
        ${
          facts.length > 0
            ? `<ul style="margin:12px 0 0;padding-left:20px;font-size:14px;line-height:1.6;color:#2E2E2E;">${facts
                .map((f) => `<li>${esc(f)}</li>`)
                .join("")}</ul>`
            : ""
        }
        <p style="margin:12px 0 0;font-size:12px;color:#667085;">Generated by AI. Always check the original message below.</p>
      </div>`
    : `<div style="margin:0 0 20px;padding:14px 18px;background:#F2F5F3;border:1px solid #C8D0CC;border-radius:12px;font-size:14px;color:#667085;">
        AI summary unavailable for this enquiry. The full message is below.
      </div>`;

  const replyBlock = triage?.suggestedReply
    ? `<div style="margin:20px 0 0;padding:16px 20px;border:1px dashed #2A8C6E;border-radius:12px;">
        <p style="margin:0 0 8px;font-size:12px;font-weight:600;color:#2A8C6E;letter-spacing:2px;text-transform:uppercase;">Suggested reply — draft, review before sending</p>
        <p style="margin:0;font-size:14px;line-height:1.6;color:#2E2E2E;">${multiline(triage.suggestedReply)}</p>
      </div>`
    : "";

  const html = `<!DOCTYPE html>
<html>
  <head><meta charset="utf-8" /><meta name="viewport" content="width=device-width, initial-scale=1" /></head>
  <body style="margin:0;padding:0;background:#F2F5F3;font-family:Arial,Helvetica,sans-serif;">
    <table width="100%" cellpadding="0" cellspacing="0"><tr><td align="center" style="padding:32px 16px;">
      <table width="600" cellpadding="0" cellspacing="0" style="max-width:600px;width:100%;background:#ffffff;border-radius:16px;overflow:hidden;border:1px solid #C8D0CC;">
        <tr><td style="background:#0D4A3A;padding:24px 32px;">
          <p style="margin:0;font-size:18px;font-weight:600;letter-spacing:4px;color:#B8CFC4;">COSMOS AI</p>
          <p style="margin:4px 0 0;font-size:11px;letter-spacing:3px;color:#2A8C6E;">NEW CONTACT ENQUIRY</p>
        </td></tr>
        <tr><td style="padding:32px;">
          <p style="margin:0 0 20px;">
            <span style="display:inline-block;padding:6px 14px;border-radius:999px;background:${badge.bg};color:${badge.fg};font-size:12px;font-weight:700;letter-spacing:1px;">${badge.label}</span>
          </p>
          <h1 style="margin:0 0 20px;font-size:22px;color:#0D4A3A;">Enquiry from ${esc(s.name)}</h1>
          ${summaryBlock}
          <div style="margin:0 0 20px;padding:16px 20px;border:1px solid #C8D0CC;border-radius:12px;">
            <p style="margin:0 0 8px;font-size:12px;font-weight:600;color:#2A8C6E;letter-spacing:2px;text-transform:uppercase;">Full message</p>
            <p style="margin:0;font-size:15px;line-height:1.6;color:#2E2E2E;word-break:break-word;">${multiline(s.message)}</p>
          </div>
          <table width="100%" cellpadding="0" cellspacing="0" style="border:1px solid #C8D0CC;border-radius:12px;">
            ${rows
              .map(
                (
                  [label, value],
                  i,
                ) => `<tr style="background:${i % 2 === 0 ? "#F2F5F3" : "#ffffff"};">
              <td style="padding:10px 16px;font-size:12px;font-weight:600;color:#2A8C6E;letter-spacing:1px;text-transform:uppercase;width:130px;">${label}</td>
              <td style="padding:10px 16px;font-size:14px;color:#2E2E2E;word-break:break-word;">${esc(value)}</td>
            </tr>`,
              )
              .join("")}
          </table>
          ${replyBlock}
          <p style="margin:24px 0 0;">
            <a href="mailto:${esc(s.email)}" style="display:inline-block;padding:11px 24px;font-size:14px;font-weight:600;color:#ffffff;text-decoration:none;border-radius:999px;background:#2E7D5E;">Reply to ${esc(s.name)}</a>
            <a href="${esc(adminUrl)}" style="display:inline-block;margin-left:8px;padding:10px 22px;font-size:14px;font-weight:600;color:#0D4A3A;text-decoration:none;border-radius:999px;border:1px solid #0D4A3A;">Open admin dashboard</a>
          </p>
        </td></tr>
        <tr><td style="background:#F2F5F3;padding:18px 32px;border-top:1px solid #C8D0CC;">
          <p style="margin:0;font-size:12px;color:#667085;">Cosmos AI · cosmosai.mw</p>
        </td></tr>
      </table>
    </td></tr></table>
  </body>
</html>`;

  const text = [
    `${badge.label}`,
    `Enquiry from ${s.name}`,
    "",
    triage ? `AI summary: ${triage.summary}` : "AI summary unavailable.",
    ...facts.map((f) => `- ${f}`),
    "",
    "FULL MESSAGE",
    s.message,
    "",
    ...rows.map(([label, value]) => `${label}: ${value}`),
    ...(triage?.suggestedReply
      ? [
          "",
          "SUGGESTED REPLY (draft, review before sending)",
          triage.suggestedReply,
        ]
      : []),
    "",
    `Admin dashboard: ${adminUrl}`,
  ].join("\n");

  return { subject, html, text };
}

export async function sendContactEmail(
  s: ContactSubmissionData,
  triage: Triage | null,
) {
  const admins = [env.ADMIN_EMAIL, env.ADMIN_EMAIL_2, env.ADMIN_EMAIL_3].filter(
    Boolean,
  ) as string[];
  if (admins.length === 0) return;

  // Likely spam still gets through (the AI can be wrong), but only to one inbox.
  const to = triage?.priority === "spam" ? admins.slice(0, 1) : admins;

  const baseUrl = process.env.NEXTAUTH_URL ?? "https://cosmosai.mw";
  const { subject, html, text } = buildContactEmail(
    s,
    triage,
    `${baseUrl}/admin`,
  );

  const { error } = await resend.emails.send({
    from: "Cosmos AI <noreply@cosmosai.mw>",
    to,
    replyTo: s.email,
    subject,
    html,
    text,
  });

  if (error) console.error("Contact notification email failed:", error);
}
